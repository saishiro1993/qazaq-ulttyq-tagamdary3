  sentenceUI.progress.textContent = `${sentenceGame.index + 1} / ${sentenceGame.order.length}`;
  sentenceUI.score.textContent = `Дұрыс: ${sentenceGame.correct}`;
  sentenceUI.answer.replaceChildren(); sentenceUI.words.replaceChildren();
